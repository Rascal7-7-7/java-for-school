public class TypeExample {
    public static void main(String args []) {
        double d = 9.9;
        char c = 'あ';
        byte b = 81;
        boolean bool = true;

        System.out.println("d: " + d);
        System.out.println("c: " + c);
        System.out.println("b: " + b);
        System.out.println("bool: " + bool);
    }
}
